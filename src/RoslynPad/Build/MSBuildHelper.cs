using System.Xml.Linq;

namespace RoslynPad.Build;

internal static class MSBuildHelper
{
    public const string DefaultSdk = "Microsoft.NET.Sdk";
    public const string ScriptCompileTaskName = "RoslynPad.BuildTasks.ScriptCompileTask";

    public static XDocument CreateCsproj(string targetFramework, IEnumerable<LibraryRef> referenceItems, IEnumerable<string> usingItems) =>
        new(new XElement("Project",
            new XAttribute("Sdk", DefaultSdk),
            BuildProperties(targetFramework),
            Reference(referenceItems),
            Using(usingItems)));

    /// <summary>
    /// Creates a csproj that compiles C# script sources: the SDK is imported explicitly so a
    /// <c>CoreCompile</c> override (invoking the app-shipped <see cref="ScriptCompileTaskName"/>
    /// task instead of <c>Csc</c>) can be defined after <c>Sdk.targets</c> and win. Imports are
    /// passed to the script compilation as a property — <c>Using</c> items would generate a
    /// regular-syntax global-usings file, which a script compilation cannot consume.
    /// </summary>
    public static XDocument CreateScriptCsproj(string targetFramework, IEnumerable<LibraryRef> referenceItems, IEnumerable<string> imports, string taskAssemblyPath) =>
        new(new XElement("Project",
            ImportSdkProject(DefaultSdk, "Sdk.props"),
            BuildProperties(targetFramework),
            ScriptProperties(imports),
            Reference(referenceItems),
            ScriptCompileItems(),
            ImportSdkProject(DefaultSdk, "Sdk.targets"),
            ScriptUsingTask(taskAssemblyPath),
            ScriptCoreCompileTarget()));

    /// <summary>
    /// Patches a csproj generated by <c>dotnet project convert</c> with RoslynPad-specific
    /// build properties, runtime reference, and additional usings.
    /// </summary>
    public static void PatchConvertedCsproj(XDocument csproj, string targetFramework, string runtimeAssemblyPath, IEnumerable<string> usingItems)
    {
        var project = csproj.Root!;

        // Remove PublishAot — not needed for RoslynPad execution
        foreach (var aot in project.Descendants("PublishAot").ToList())
        {
            aot.Remove();
        }

        // Add build properties to first PropertyGroup (or create one)
        var props = project.Element("PropertyGroup");
        if (props is null)
        {
            props = new XElement("PropertyGroup");
            project.AddFirst(props);
        }

        SetBuildProperties(props, targetFramework);

        // Add RoslynPad.Runtime reference
        project.Add(new XElement("ItemGroup",
            new XElement("Reference",
                new XAttribute("Include", "RoslynPad.Runtime"),
                new XElement("HintPath", runtimeAssemblyPath))));

        // Add implicit usings
        project.Add(Using(usingItems));
    }

    /// <summary>
    /// Converts a csproj using the <c>Sdk</c> attribute (e.g. from <c>dotnet project convert</c>)
    /// into script form: the implicit SDK import is expanded into explicit
    /// <c>Sdk.props</c>/<c>Sdk.targets</c> imports (an <c>Sdk</c> attribute imports its targets
    /// after the project body, which would override a body-defined <c>CoreCompile</c>), the
    /// <c>Using</c> items are converted to the imports property, and the script compile items,
    /// task registration, and <c>CoreCompile</c> override are appended.
    /// </summary>
    public static void ConvertToScriptCsproj(XDocument csproj, string taskAssemblyPath)
    {
        var project = csproj.Root!;

        var sdks = project.Attribute("Sdk")?.Value.Split(';', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries) ?? [DefaultSdk];
        project.Attribute("Sdk")?.Remove();

        var usings = project.Descendants("Using").ToList();
        var imports = usings.Select(u => u.Attribute("Include")?.Value).Where(v => !string.IsNullOrEmpty(v)).Select(v => v!).ToArray();
        usings.ForEach(u => u.Remove());

        foreach (var sdk in sdks.Reverse())
        {
            project.AddFirst(ImportSdkProject(sdk, "Sdk.props"));
        }

        project.Add(ScriptProperties(imports));
        project.Add(ScriptCompileItems());

        foreach (var sdk in sdks)
        {
            project.Add(ImportSdkProject(sdk, "Sdk.targets"));
        }

        project.Add(ScriptUsingTask(taskAssemblyPath));
        project.Add(ScriptCoreCompileTarget());
    }

    public const string ScriptInitFileName = "ScriptInit.csx";
    public const string ScriptFileName = "Program.csx";

    private static XElement ScriptProperties(IEnumerable<string> imports) =>
        new("PropertyGroup",
            new XElement("RoslynPadImports", string.Join(";", imports)),
            new XElement("EnableDefaultCompileItems", "false"),
            new XElement("ProduceReferenceAssembly", "false"));

    private static XElement ScriptCompileItems() =>
        new("ItemGroup",
            new XElement("Compile", new XAttribute("Include", ScriptInitFileName)),
            new XElement("Compile", new XAttribute("Include", ScriptFileName)));

    private static XElement ScriptUsingTask(string taskAssemblyPath) =>
        new("UsingTask",
            new XAttribute("TaskName", ScriptCompileTaskName),
            new XAttribute("AssemblyFile", taskAssemblyPath));

    private static XElement ScriptCoreCompileTarget() =>
        new("Target",
            new XAttribute("Name", "CoreCompile"),
            new XAttribute("DependsOnTargets", "$(CoreCompileDependsOn)"),
            new XAttribute("Inputs", "$(MSBuildAllProjects);@(Compile);@(ReferencePathWithRefAssemblies)"),
            new XAttribute("Outputs", "@(IntermediateAssembly)"),
            new XAttribute("Condition", "'$(SkipCompilerExecution)' != 'true'"),
            new XElement("ScriptCompileTask",
                new XAttribute("Sources", "@(Compile)"),
                new XAttribute("References", "@(ReferencePathWithRefAssemblies)"),
                new XAttribute("OutputAssembly", "@(IntermediateAssembly)"),
                new XAttribute("Optimize", "$(Optimize)"),
                new XAttribute("CheckOverflow", "$(CheckForOverflowUnderflow)"),
                new XAttribute("AllowUnsafe", "$(AllowUnsafeBlocks)"),
                new XAttribute("Prefer32Bit", "$(RoslynPadPrefer32Bit)"),
                new XAttribute("Imports", "$(RoslynPadImports)"),
                new XAttribute("NoWarn", "$(NoWarn)"),
                new XAttribute("WorkingDirectory", "$(RoslynPadWorkingDirectory)")));

    private static XElement Reference(IEnumerable<LibraryRef> referenceItems) =>
        new("ItemGroup",
            referenceItems.Select(Reference).ToArray());

    private static XElement Reference(LibraryRef reference)
    {
        var element = new XElement(reference.Kind.ToString(),
            new XAttribute("Include", reference.Value));

        if (!string.IsNullOrEmpty(reference.Version))
        {
            element.Add(new XAttribute("Version", reference.Version));
        }

        return element;
    }

    private static XElement Using(IEnumerable<string> usingItems) =>
        new("ItemGroup",
            usingItems.Select(c => new XElement("Using", new XAttribute("Include", c))));

    private static XElement BuildProperties(string targetFramework)
    {
        var props = new XElement("PropertyGroup");
        SetBuildProperties(props, targetFramework);
        return props;
    }

    private static void SetBuildProperties(XElement props, string targetFramework)
    {
        SetOrAdd(props, "TargetFramework", targetFramework);
        SetOrAdd(props, "OutputType", "Exe");
        SetOrAdd(props, "OutputPath", "bin");
        SetOrAdd(props, "UseAppHost", "false");
        SetOrAdd(props, "AllowUnsafeBlocks", "true");
        SetOrAdd(props, "LangVersion", "preview");
        SetOrAdd(props, "Features", "updated-memory-safety-rules");
        SetOrAdd(props, "Nullable", "enable");
        SetOrAdd(props, "AppendTargetFrameworkToOutputPath", "false");
        SetOrAdd(props, "AppendRuntimeIdentifierToOutputPath", "false");
        SetOrAdd(props, "AppendPlatformToOutputPath", "false");
        SetOrAdd(props, "CopyBuildOutputToOutputDirectory", "true");
        SetOrAdd(props, "GenerateAssemblyInfo", "false");
    }

    private static void SetOrAdd(XElement parent, string name, string value)
    {
        var existing = parent.Element(name);
        if (existing is not null)
        {
            existing.Value = value;
        }
        else
        {
            parent.Add(new XElement(name, value));
        }
    }

    private static XElement ImportSdkProject(string sdk, string project) =>
        new("Import",
            new XAttribute("Sdk", sdk),
            new XAttribute("Project", project));
}
